-- Add initial tracking entry for orders without history

INSERT INTO order_status_history (order_id, status, note)
SELECT o.id, o.status, 'Initial order status'
FROM orders AS o
WHERE NOT EXISTS (
    SELECT 1
    FROM order_status_history AS h
    WHERE h.order_id = o.id
);


-- Create pending mentor profiles for existing mentors

INSERT INTO mentor_profiles (user_id, status)
SELECT u.id, 'pending'
FROM users AS u
WHERE u.role = 'mentor'
AND NOT EXISTS (
    SELECT 1
    FROM mentor_profiles AS mp
    WHERE mp.user_id = u.id
);


-- Create pending seller approvals for existing sellers

INSERT INTO seller_approvals (seller_id, status)
SELECT u.id, 'pending'
FROM users AS u
WHERE u.role = 'seller'
AND NOT EXISTS (
    SELECT 1
    FROM seller_approvals AS sa
    WHERE sa.seller_id = u.id
);



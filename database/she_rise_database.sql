-- ============================================================
-- 6. UPDATED_AT TRIGGERS
-- ============================================================

DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'users',
        'login_attempts',
        'products',
        'buyer_addresses',
        'cart',
        'orders',
        'custom_requests',
        'reviews',
        'return_requests',
        'mentor_profiles',
        'mentorship_requests',
        'mentorship_sessions',
        'seller_approvals',
        'complaints'
    ]
    LOOP
        EXECUTE format(
            'DROP TRIGGER IF EXISTS trg_%I_updated_at ON %I',
            t, t
        );

        EXECUTE format(
            'CREATE TRIGGER trg_%I_updated_at
             BEFORE UPDATE ON %I
             FOR EACH ROW
             EXECUTE FUNCTION set_updated_at()',
            t, t
        );
    END LOOP;
END;
$$;



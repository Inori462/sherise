-- ============================================================
-- 0. HELPER: auto-update "updated_at"
-- (replaces MySQL's ON UPDATE CURRENT_TIMESTAMP)
-- ============================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

